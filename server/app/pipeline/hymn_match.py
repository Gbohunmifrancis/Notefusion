"""Hymn recognition: does a sung take match a hymn we hold, and what is its hymnbook version?

Church choirs mostly sing hymns, and a hymn's published score is exactly right where a
transcription is a reading: notes, rhythm, bar lines, pickup and time signature (the
worker writes every take in 4/4 unless told otherwise).  So after a melody transcription
the take's tune is looked up in ``app/data/hymn_index.json`` — generated by
``tools/blog/build.mjs`` from every published hymn (``tools/blog/lib/hymn-index.mjs``) —
and when it matches one clearly the result carries ``hymn_match``: the hymn, its credit,
and (for an entry with a whole score) the hymnbook melody written in the key that was
sung, for the clients' "Use the hymnbook version?" prompt.

Matching is key- and tempo-invariant and tolerant of wrong, missed and extra notes and of
a partial take (one verse, the refrain, a start mid-hymn, or several verses):

* Both melodies are reduced to their contour: repeated pitches are merged (a singer's
  re-struck note and a held one transcribe either way), leaving the interval between
  successive notes (key-invariant) and the log ratio of successive note lengths
  (tempo-invariant).
* A prefilter scores every entry by the rarer interval trigrams it shares with the take
  (idf-weighted, one sparse product), so only the best ``CANDIDATES`` are aligned —
  fast with ten thousand entries.
* Smith-Waterman local alignment over the intervals, vectorised across the candidates: an
  exact interval scores 1 (plus a little when the rhythm agrees too), a semitone off
  ``SEMITONE``, anything else ``MISMATCH``, a gap ``GAP``.  A score entry's melody is
  tiled so a take of several verses aligns as one run.
* A match is offered only when it is long (``MIN_MATCHED`` exact intervals), dense
  (score per aligned interval), covers most of the take, and clearly beats the best entry
  with a *different* tune (two hymns sung to one tune are the same melody, not rivals).
  ``kind="incipit"`` entries (recognition only: an opening phrase, a title and a link)
  must have their whole opening matched from its first note and clear a stricter margin;
  they name the tune and never carry a score.

The transposition is the median pitch difference over the matched notes, so the
hymnbook version comes back in the key the take was sung in, whatever the transcription
decided its doh was.  Pure symbolic work on the note list: milliseconds, never the job.
"""

from __future__ import annotations

import json
import logging
import math
from dataclasses import asdict, dataclass, field
from functools import lru_cache
from pathlib import Path

import numpy as np

logger = logging.getLogger(__name__)

INDEX_PATH = Path(__file__).resolve().parent.parent / "data" / "hymn_index.json"

# ── Alignment scores ──────────────────────────────────────────────────────────
MATCH = 1.0
SEMITONE = -0.4          # an interval a semitone off: a sloppy step, half forgiven
MISMATCH = -1.0
GAP = 0.8                # per missed or extra interval (linear)
RHYTHM_BONUS = 0.3       # an exact interval whose note-length ratio agrees too
RHYTHM_TOLERANCE = 0.45  # |log2 ratio| difference that counts as agreeing (about 1.37x)
INTERVAL_CLIP = 12       # an interval past an octave is a glitch, not a leap to match

# ── Acceptance (measured: see tests/test_hymn_match.py and the hand-back) ─────
MIN_MATCHED = 10         # exact intervals in the alignment: eleven notes of the tune
MIN_DENSITY = 0.62       # alignment score per aligned interval (take or hymn side, the longer)
MIN_COVERAGE = 0.45      # share of the take's intervals inside the alignment
MARGIN_RATIO = 1.3       # best / best of another tune
INCIPIT_MIN_MATCHED = 9
INCIPIT_MIN_DENSITY = 0.8
INCIPIT_MIN_COVER = 0.85  # share of the incipit's intervals inside the alignment
INCIPIT_MARGIN_RATIO = 1.6
SAME_TUNE_SHARE = 0.6    # two entries whose melodies align this well are one tune

CANDIDATES = 40          # aligned by intervals after the prefilter
FINE = 8                 # of those, aligned by pitch class under all twelve transpositions
GRAM = 3                 # interval n-gram length for the prefilter
MAX_TILES = 4            # verses a take may run through in one alignment


@dataclass(frozen=True)
class Entry:
    kind: str            # "score" | "incipit"
    slug: str
    title: str
    tune: str
    url: str
    source: str
    licence: str
    credit: str
    notes: tuple[tuple[int, float, float], ...]
    checked: bool = False
    key: str = ""
    time: str = ""
    pickup: float = 0.0
    tempo: int = 0
    lyrics: str = ""


@dataclass(frozen=True)
class Contour:
    """A melody with repeats merged: its pitches, the intervals between them, and length ratios."""

    pitches: np.ndarray      # int, one per merged note
    starts: np.ndarray       # float, the merged note's start (beats or seconds)
    intervals: np.ndarray    # int, len(pitches) - 1, clipped to ±INTERVAL_CLIP
    rhythm: np.ndarray       # float per note: log2(its length / the previous note's); nan for the first or unknown

    @property
    def interval_rhythm(self) -> np.ndarray:
        """The rhythm of each interval: the length ratio of the two notes it joins."""
        return self.rhythm[1:]


def contour(notes) -> Contour:
    """``notes`` as (pitch, start, duration) in time order (any unit)."""
    ordered = sorted(((int(p), float(s), float(d)) for p, s, d in notes), key=lambda n: n[1])
    pitches: list[int] = []
    starts: list[float] = []
    ends: list[float] = []
    for p, s, d in ordered:
        if pitches and p == pitches[-1]:
            ends[-1] = max(ends[-1], s + d)
            continue
        pitches.append(p)
        starts.append(s)
        ends.append(s + d)
    n = len(pitches)
    lengths = np.array(
        [(starts[k + 1] - starts[k]) if k + 1 < n else (ends[k] - starts[k]) for k in range(n)], dtype=float)
    lengths = np.where(lengths > 1e-6, lengths, np.nan)
    p = np.array(pitches, dtype=int)
    intervals = np.clip(np.diff(p), -INTERVAL_CLIP, INTERVAL_CLIP) if n > 1 else np.zeros(0, dtype=int)
    rhythm = np.full(n, np.nan)
    if n > 1:
        with np.errstate(invalid="ignore", divide="ignore"):
            rhythm[1:] = np.log2(lengths[1:] / lengths[:-1])
    return Contour(p, np.array(starts, dtype=float), intervals.astype(int), rhythm)


def _grams(intervals: np.ndarray) -> set[tuple[int, ...]]:
    return {tuple(int(x) for x in intervals[k:k + GRAM]) for k in range(len(intervals) - GRAM + 1)}


class HymnIndex:
    """The entries, their contours and the trigram prefilter."""

    def __init__(self, entries: list[Entry]):
        from scipy import sparse

        self.entries = entries
        self.contours = [contour(e.notes) for e in entries]
        vocab: dict[tuple[int, ...], int] = {}
        rows, cols = [], []
        for i, (e, c) in enumerate(zip(entries, self.contours)):
            ivs = c.intervals
            if e.kind == "score" and len(c.pitches) > 1:
                # A take running from the last line into the next verse crosses the join.
                ivs = np.concatenate([ivs, [c.pitches[0] - c.pitches[-1]], ivs[:GRAM]])
            for g in _grams(ivs):
                rows.append(i)
                cols.append(vocab.setdefault(g, len(vocab)))
        self.vocab = vocab
        presence = sparse.csr_matrix(
            (np.ones(len(rows)), (rows, cols)), shape=(len(entries), max(1, len(vocab))))
        presence.data[:] = 1.0
        df = np.asarray(presence.sum(axis=0)).ravel()
        idf = np.log((len(entries) + 1) / (df + 1)) + 0.1
        self.weighted = presence.multiply(idf[None, :]).tocsr()
        self.idf = idf
        self._same: dict[tuple[int, int], bool] = {}

    def prefilter(self, query: Contour, k: int = CANDIDATES) -> list[int]:
        cols = [self.vocab[g] for g in _grams(query.intervals) if g in self.vocab]
        if not cols:
            return []
        v = np.zeros(self.weighted.shape[1])
        v[cols] = 1.0
        scores = self.weighted @ v
        k = min(k, int(np.count_nonzero(scores)))
        if k <= 0:
            return []
        top = np.argpartition(-scores, k - 1)[:k]
        return [int(i) for i in top[np.argsort(-scores[top], kind="stable")]]

    def same_tune(self, a: int, b: int) -> bool:
        """Whether two entries carry one melody (one tune, two hymns; or a variant of it)."""
        key = (min(a, b), max(a, b))
        if key not in self._same:
            ca, cb = self.contours[a], self.contours[b]
            short = min(len(ca.intervals), len(cb.intervals))
            if short < GRAM:
                self._same[key] = False
            else:
                score = float(_sw_scores(ca.intervals, ca.interval_rhythm, [cb.intervals], [cb.interval_rhythm])[0])
                self._same[key] = score >= SAME_TUNE_SHARE * short * MATCH
        return self._same[key]


def _entry(d: dict) -> Entry:
    return Entry(
        kind=d["kind"], slug=d["slug"], title=d["title"], tune=d.get("tune", ""), url=d["url"],
        source=d["source"], licence=d["licence"], credit=d["credit"],
        notes=tuple((int(p), float(s), float(l)) for p, s, l in d["notes"]),
        checked=bool(d.get("checked", False)), key=d.get("key", ""), time=d.get("time", ""),
        pickup=float(d.get("pickup", 0) or 0), tempo=int(d.get("tempo", 0) or 0), lyrics=d.get("lyrics", ""))


def load_index(path: Path = INDEX_PATH) -> HymnIndex:
    data = json.loads(path.read_text(encoding="utf-8"))
    entries = [_entry(d) for d in data["entries"] if d.get("kind") in ("score", "incipit")]
    return HymnIndex(entries)


@lru_cache(maxsize=1)
def default_index() -> HymnIndex:
    return load_index()


# ── Alignment ─────────────────────────────────────────────────────────────────


def _pad(rows: list[np.ndarray], fill: float) -> tuple[np.ndarray, np.ndarray]:
    width = max((len(r) for r in rows), default=0)
    out = np.full((len(rows), width), fill, dtype=float)
    valid = np.zeros((len(rows), width), dtype=bool)
    for k, r in enumerate(rows):
        out[k, :len(r)] = r
        valid[k, :len(r)] = True
    return out, valid


def _substitution(qv: float, qr: float, t: np.ndarray, tr: np.ndarray, valid: np.ndarray, circular: bool) -> np.ndarray:
    """Score of the take's symbol ``qv`` against every target symbol: exact, a semitone off, or wrong.

    ``circular`` compares pitch classes (a semitone either side of the octave too).
    """
    d = np.abs(t - qv)
    if circular:
        d = np.minimum(d % 12, 12 - d % 12)
    s = np.where(d == 0, MATCH, np.where(d == 1, SEMITONE, MISMATCH))
    if not math.isnan(qr):
        with np.errstate(invalid="ignore"):
            agree = (d == 0) & (np.abs(tr - qr) <= RHYTHM_TOLERANCE)
        s = s + np.where(agree, RHYTHM_BONUS, 0.0)
    return np.where(valid, s, MISMATCH)


def _sw_scores(q, qr, targets, trhythm, circular: bool = False) -> np.ndarray:
    """Best local-alignment score of ``q`` against each target, all targets at once.

    Each row of the matrix is computed with numpy for every target together: the diagonal and
    the gap from above need only the previous row, and the gap from the left is a running maximum
    (H[j] = max over k <= j of E[k] - GAP * (j - k)), so no cell loop is needed.
    """
    t, valid = _pad(targets, 0.0)
    tr, _ = _pad(trhythm, np.nan)
    k, m = t.shape
    if k == 0 or m == 0:
        return np.zeros(k)
    j = GAP * np.arange(1, m + 1)
    prev = np.zeros((k, m + 1))
    best = np.zeros(k)
    for i in range(len(q)):
        s = _substitution(float(q[i]), float(qr[i]), t, tr, valid, circular)
        e = np.maximum(np.maximum(prev[:, :-1] + s, prev[:, 1:] - GAP), 0.0)
        cur = np.zeros((k, m + 1))
        cur[:, 1:] = np.maximum.accumulate(e + j, axis=1) - j
        best = np.maximum(best, cur.max(axis=1))
        prev = cur
    return best


@dataclass
class Alignment:
    score: float
    pairs: list[tuple[int, int]]   # (take note, target note), exact matches only
    q_span: tuple[int, int]        # take notes [start, end)
    t_span: tuple[int, int]        # target notes [start, end)


def _sw_align(q, qr, t, tr, circular: bool) -> Alignment:
    """The best local alignment with its traceback, for one target."""
    n, m = len(q), len(t)
    j = GAP * np.arange(1, m + 1)
    h = np.zeros((n + 1, m + 1))
    subs = np.zeros((n, m))
    valid = np.ones((1, m), dtype=bool)
    for i in range(n):
        s = _substitution(float(q[i]), float(qr[i]), t[None, :], tr[None, :], valid, circular)[0]
        subs[i] = s
        e = np.maximum(np.maximum(h[i, :-1] + s, h[i, 1:] - GAP), 0.0)
        h[i + 1, 1:] = np.maximum.accumulate(e + j) - j
    i, jj = (int(x) for x in np.unravel_index(int(np.argmax(h)), h.shape))
    score = float(h[i, jj])
    end = (i, jj)
    pairs: list[tuple[int, int]] = []
    while i > 0 and jj > 0 and h[i, jj] > 1e-9:
        here = h[i, jj]
        if abs(here - (h[i - 1, jj - 1] + subs[i - 1, jj - 1])) < 1e-9:
            if subs[i - 1, jj - 1] >= MATCH - 1e-9:
                pairs.append((i - 1, jj - 1))
            i, jj = i - 1, jj - 1
        elif abs(here - (h[i - 1, jj] - GAP)) < 1e-9:
            i -= 1
        else:
            jj -= 1
    pairs.reverse()
    return Alignment(score, pairs, (i, end[0]), (jj, end[1]))


def _copies(entry: Entry, c: Contour, take: Contour) -> int:
    """How many verses of a score entry a take may run through (an incipit is never repeated)."""
    if entry.kind != "score":
        return 1
    return max(1, min(MAX_TILES, math.ceil(len(take.pitches) / max(1, len(c.pitches))) + 1))


def _tiled_intervals(c: Contour, copies: int) -> tuple[np.ndarray, np.ndarray]:
    if copies <= 1 or len(c.pitches) < 2:
        return c.intervals, c.interval_rhythm
    join = np.array([np.clip(c.pitches[0] - c.pitches[-1], -INTERVAL_CLIP, INTERVAL_CLIP)])
    ivs = np.concatenate([np.concatenate([c.intervals, join])] * (copies - 1) + [c.intervals])
    rhy = np.concatenate([np.concatenate([c.interval_rhythm, [np.nan]])] * (copies - 1) + [c.interval_rhythm])
    return ivs.astype(int), rhy


# ── Matching ──────────────────────────────────────────────────────────────────


@dataclass
class Match:
    entry: Entry
    score: float
    density: float
    coverage: float
    matched: int
    transpose: int                 # semitones from the entry's pitches to the take's
    seconds_per_beat: float | None  # the take's pace against the entry's beats, when known
    runner_up: str | None
    runner_up_score: float
    confidence: float


def match(notes, seconds_per_unit: float = 1.0, index: HymnIndex | None = None, explain: bool = False):
    """The hymn ``notes`` (``(pitch, start, duration)``) are a rendition of, or None.

    ``seconds_per_unit`` converts the take's time unit to seconds (60 / tempo for beats), for the
    pace the hymnbook version is played back at. ``explain`` returns the best candidate's figures
    even when it is refused (for measuring the thresholds), as ``(match_or_None, figures)``.
    """
    index = index or default_index()
    q = contour(notes)
    refused = (None, None) if explain else None
    if len(q.intervals) < min(MIN_MATCHED, INCIPIT_MIN_MATCHED):
        return refused
    ids = index.prefilter(q)
    if not ids:
        return refused
    entries = index.entries

    # Stage 1: intervals (key-free) against every prefiltered candidate, to rank them.
    tiled = [_tiled_intervals(index.contours[i], _copies(entries[i], index.contours[i], q)) for i in ids]
    coarse = _sw_scores(q.intervals, q.interval_rhythm, [t for t, _ in tiled], [r for _, r in tiled])
    ranked = [ids[k] for k in np.argsort(-coarse, kind="stable")[:FINE]]

    # Stage 2: pitch classes under each of the twelve transpositions. A wrong note costs one
    # mismatch here where it costs two intervals above, so this is the score that is judged.
    rows, rhythms, owners = [], [], []
    for i in ranked:
        c = index.contours[i]
        copies = _copies(entries[i], c, q)
        rhy = np.tile(c.rhythm, copies)
        for shift in range(12):
            rows.append(np.tile((c.pitches + shift) % 12, copies).astype(float))
            rhythms.append(rhy)
            owners.append((i, shift))
    fine = _sw_scores(q.pitches % 12, q.rhythm, rows, rhythms, circular=True)
    per_entry: dict[int, tuple[float, int]] = {}
    for (i, shift), score in zip(owners, fine):
        if i not in per_entry or score > per_entry[i][0] + 1e-9:
            per_entry[i] = (float(score), shift)
    order = sorted(per_entry, key=lambda i: (-round(per_entry[i][0], 6), not entries[i].checked,
                                             entries[i].kind != "score", entries[i].slug))
    best_id = order[0]
    best = entries[best_id]
    runner, runner_score = None, 0.0
    for i in order[1:]:
        if not index.same_tune(best_id, i):
            runner, runner_score = entries[i].slug, per_entry[i][0]
            break

    c = index.contours[best_id]
    copies = _copies(best, c, q)
    shift = per_entry[best_id][1]
    target = np.tile((c.pitches + shift) % 12, copies).astype(float)
    aln = _sw_align(q.pitches % 12, q.rhythm, target, np.tile(c.rhythm, copies), circular=True)
    q_len = aln.q_span[1] - aln.q_span[0]
    t_len = aln.t_span[1] - aln.t_span[0]
    density = aln.score / max(1, q_len, t_len)
    coverage = q_len / max(1, len(q.pitches))
    matched = len(aln.pairs)
    margin = aln.score / max(runner_score, 1e-9)
    figures = {"slug": best.slug, "score": round(aln.score, 2), "density": round(density, 3),
               "coverage": round(coverage, 3), "matched": matched, "margin": round(margin, 2),
               "runner_up": runner, "runner_up_score": round(runner_score, 2)}
    if best.kind == "incipit":
        own = len(c.pitches)
        ok = (own >= INCIPIT_MIN_MATCHED + 1 and matched >= INCIPIT_MIN_MATCHED
              and density >= INCIPIT_MIN_DENSITY and aln.t_span[0] <= 1
              and t_len >= INCIPIT_MIN_COVER * own and margin >= INCIPIT_MARGIN_RATIO)
    else:
        ok = (matched >= MIN_MATCHED and density >= MIN_DENSITY and coverage >= MIN_COVERAGE
              and margin >= MARGIN_RATIO)
    if not ok:
        return (None, figures) if explain else None

    n_notes = len(c.pitches)
    diffs, paces = [], []
    previous = None
    for qi, ti in aln.pairs:
        verse, at = divmod(ti, n_notes)
        diffs.append(int(q.pitches[qi]) - int(c.pitches[at]))
        if previous is not None and previous[1] == verse and at > previous[2]:
            beats = float(c.starts[at] - c.starts[previous[2]])
            took = float(q.starts[qi] - q.starts[previous[0]]) * seconds_per_unit
            if beats > 0 and took > 0:
                paces.append(took / beats)
        previous = (qi, verse, at)
    transpose = int(round(float(np.median(diffs)))) if diffs else shift
    # The pitch-class alignment fixed the transposition up to octaves; the median picks the octave.
    transpose = shift + 12 * round((transpose - shift) / 12)
    pace = float(np.median(paces)) if paces else None
    confidence = round(max(0.0, min(1.0, density)) * (1.0 - min(1.0, runner_score / max(aln.score, 1e-9))), 3)
    found = Match(best, round(aln.score, 3), round(density, 3), round(coverage, 3), matched, transpose,
                  pace, runner, round(runner_score, 3), confidence)
    return (found, figures) if explain else found


# ── The hymnbook version, in the sung key ─────────────────────────────────────

# A key name for a doh nobody gave a name to: the signature with the fewer accidentals.
_MAJOR_NAMES = ["C", "Db", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B"]
_MINOR_NAMES = ["C", "C#", "D", "Eb", "E", "F", "F#", "G", "G#", "A", "Bb", "B"]


def sung_key(hymn_key: str, transpose: int, heard_key: str | None) -> str:
    """The hymn's key moved by ``transpose``, named as the transcription named it when the same."""
    from app.pipeline.transcriber import _parse_key_override

    k = _parse_key_override(hymn_key)
    tonic = (k.tonic.pitchClass + transpose) % 12
    if heard_key:
        try:
            h = _parse_key_override(heard_key)
            if h.mode == k.mode and h.tonic.pitchClass == tonic:
                return heard_key
        except Exception:  # noqa: BLE001 - a key we cannot read is simply not reused
            pass
    names = _MAJOR_NAMES if k.mode == "major" else _MINOR_NAMES
    return f"{names[tonic]} {k.mode}"


def _engrave(notes: list[tuple[int, float, float]], key_name: str, time_signature: str, pickup: float, tempo: int) -> str:
    """MusicXML for the hymnbook melody: its bars, ties and pickup, spelled in ``key_name``."""
    from music21 import key as m21key, meter, note, stream, tempo as m21tempo

    from app.pipeline.transcriber import _parse_key_override, _respell_to_key, export_musicxml

    k = _parse_key_override(key_name)
    s = stream.Stream()
    s.insert(0, m21tempo.MetronomeMark(number=tempo))
    ts = meter.TimeSignature(time_signature)
    s.insert(0, ts)
    s.insert(0, m21key.Key(k.tonic.name, k.mode))
    for p, start, dur in notes:
        n = note.Note()
        n.pitch.midi = p
        n.quarterLength = dur
        s.insert(start, n)
    _respell_to_key(s, k)
    score = s.makeMeasures()
    score.makeTies(inPlace=True)
    measures = list(score.getElementsByClass(stream.Measure))
    lead = float(ts.barDuration.quarterLength) - pickup if pickup else 0.0
    if measures and lead > 1e-9:
        # The pickup is a short first bar (an anacrusis), not a bar opening with rests.
        first = measures[0]
        for r in list(first.getElementsByClass("Rest")):
            if float(r.offset) < lead - 1e-9:
                first.remove(r)
        for el in list(first.notesAndRests):
            first.setElementOffset(el, float(el.offset) - lead)
        first.paddingLeft = lead
        first.number = 0
        for i, m in enumerate(measures[1:], start=1):
            m.number = i
    score.makeAccidentals(inPlace=True, alteredPitches=k.alteredPitches)
    return export_musicxml(score)


def _label(notes: list[tuple[int, float, float]], key_name: str, time_signature: str):
    from app.config import settings
    from app.pipeline import solfa, solfa_render
    from app.pipeline.transcriber import TranscribedNote, _parse_key_override

    k = _parse_key_override(key_name)
    doh_pc = solfa.doh_pitch_class(k.tonic.pitchClass, k.mode)
    pitches = [p for p, _, _ in notes]
    ref = solfa.reference_doh(pitches, doh_pc, k.mode)
    flags = solfa.ascending_flags(pitches, doh_pc)
    labelled = []
    for (p, start, dur), flag in zip(notes, flags):
        syl, mark, degree = solfa.syllable(p, doh_pc, ref, solfa.resolve_ascending(flag, settings.chromatic_spelling))
        labelled.append(TranscribedNote(p, start, dur, degree, syl, mark, 1.0))
    half_grid = all(abs(x * 2 - round(x * 2)) < 1e-9 for _, s, d in notes for x in (s, d))
    lines = solfa_render.render_lines(
        labelled, solfa.doh_header(doh_pc), time_signature=time_signature, divisions_per_beat=2 if half_grid else 4)
    return labelled, lines


def offer(result, index: HymnIndex | None = None) -> dict | None:
    """``hymn_match`` for a finished transcription, or None when no hymn matches clearly.

    For a score entry it carries the hymnbook version in the key the take was sung in: ``key``,
    ``time_signature``, ``tempo`` (the take's pace), ``pickup``, ``notes`` (labelled like a
    transcription's), ``solfa_lines``, ``musicxml`` and ``lyrics`` (the first verse, one syllable a
    note). An incipit entry names the tune and links to it, and carries none of those.
    """
    notes = [(n.pitch_midi, n.start_beat, n.dur_beats) for n in result.notes]
    tempo = float(result.tempo or 0)
    m = match(notes, seconds_per_unit=60.0 / tempo if tempo > 0 else 1.0, index=index)
    if m is None:
        return None
    e = m.entry
    out = {
        "slug": e.slug, "title": e.title, "tune": e.tune, "url": e.url, "source": e.source,
        "licence": e.licence, "credit": e.credit, "kind": e.kind, "confidence": m.confidence,
    }
    if e.kind != "score":
        return out
    key_name = sung_key(e.key, m.transpose, result.key)
    moved = [(p + m.transpose, s, d) for p, s, d in e.notes]
    labelled, lines = _label(moved, key_name, e.time)
    bpm = int(round(60.0 / m.seconds_per_beat)) if m.seconds_per_beat else e.tempo
    bpm = max(30, min(240, bpm or e.tempo or 80))
    out.update({
        "key": key_name,
        "time_signature": e.time,
        "tempo": bpm,
        "pickup": e.pickup,
        "notes": [asdict(n) for n in labelled],
        "solfa_lines": lines,
        "musicxml": _engrave(moved, key_name, e.time, e.pickup, bpm),
        "lyrics": e.lyrics,
    })
    return out
