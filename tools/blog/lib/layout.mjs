// The page shell for generated pages: the same branded header and footer as the policy pages
// (assets/site-pages.css), the blog's own styles, SEO head tags, and the first-party tracker.
import { ORIGIN, SITE_NAME, DEFAULT_OG, ADSENSE_CLIENT, ASSET_VERSION } from "./site.mjs";
import { escapeHtml, jsonForScript } from "./util.mjs";

const NAV = [
  ["/#how", "How it works"],
  ["/#solfa", "Tonic Solfa"],
  ["/#pricing", "Pricing"],
  ["/blog", "Blog"],
  ["/hymns", "Hymns"],
];

function nav(active, cls, label) {
  const links = NAV.map(([href, text]) => `<a href="${href}"${href === active ? ' aria-current="page"' : ""}>${text}</a>`).join("");
  return `<nav class="${cls}" aria-label="${label}">${links}`;
}

export const GENERATED_NOTE = "<!-- Generated by tools/blog/build.mjs from content/. Edit the source and rebuild; do not edit this file. -->";

/**
 * A full page. `path` is the canonical path ("/blog/how-to-read-tonic-solfa"); `jsonLd` is a list
 * of schema.org objects; `head` and `scripts` are extra raw HTML.
 */
export function page({ path, title, description, ogType = "website", image = DEFAULT_OG, jsonLd = [], robots = null, head = "", body, active = null, scripts = "", article = null }) {
  const url = ORIGIN + path;
  const img = image.src.startsWith("http") ? image.src : ORIGIN + image.src;
  const meta = [
    `<meta charset="utf-8">`,
    `<meta name="viewport" content="width=device-width, initial-scale=1">`,
    `<title>${escapeHtml(title)}</title>`,
    `<meta name="description" content="${escapeHtml(description)}">`,
    `<link rel="canonical" href="${url}">`,
    robots ? `<meta name="robots" content="${robots}">` : "",
    `<meta property="og:type" content="${ogType}">`,
    `<meta property="og:site_name" content="${SITE_NAME}">`,
    `<meta property="og:locale" content="en_NG">`,
    `<meta property="og:title" content="${escapeHtml(title)}">`,
    `<meta property="og:description" content="${escapeHtml(description)}">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:image" content="${img}">`,
    `<meta property="og:image:width" content="${image.width}">`,
    `<meta property="og:image:height" content="${image.height}">`,
    `<meta property="og:image:alt" content="${escapeHtml(image.alt)}">`,
    article ? `<meta property="article:published_time" content="${article.published}">` : "",
    article ? `<meta property="article:modified_time" content="${article.modified}">` : "",
    ...(article ? article.tags.map((t) => `<meta property="article:tag" content="${escapeHtml(t)}">`) : []),
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${escapeHtml(title)}">`,
    `<meta name="twitter:description" content="${escapeHtml(description)}">`,
    `<meta name="twitter:image" content="${img}">`,
    `<meta name="theme-color" content="#2563EB">`,
    `<link rel="icon" href="/assets/favicon.ico" sizes="16x16 32x32 48x48">`,
    `<link rel="icon" type="image/png" href="/assets/icon-192.png" sizes="192x192">`,
    `<link rel="apple-touch-icon" href="/assets/apple-touch-icon.png">`,
    `<link rel="alternate" type="application/rss+xml" title="NoteFusion blog" href="/blog/feed.xml">`,
    `<link rel="preconnect" href="https://fonts.googleapis.com">`,
    `<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>`,
    `<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet">`,
    `<link rel="stylesheet" href="/assets/site-pages.css?v=${ASSET_VERSION.sitePagesCss}">`,
    `<link rel="stylesheet" href="/assets/blog.css?v=${ASSET_VERSION.blogCss}">`,
    head,
    ...jsonLd.map((d) => `<script type="application/ld+json">\n${jsonForScript(d)}\n</script>`),
    ADSENSE_CLIENT ? `<!-- Google AdSense (public pages only; never the signed-in /app). -->\n<script async src="https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=${ADSENSE_CLIENT}" crossorigin="anonymous"></script>` : "",
  ].filter(Boolean).join("\n");

  return `<!DOCTYPE html>
<html lang="en-GB">
<head>
${GENERATED_NOTE}
${meta}
</head>
<body class="site-document blog-page">
<a class="skip-link" href="#main">Skip to content</a>
<header class="site-header">
  <div class="site-shell-inner">
    <a class="site-brand" href="/" aria-label="NoteFusion home">
      <span class="site-brand-mark" aria-hidden="true"></span>
      <span class="site-brand-name">NoteFusion</span>
    </a>
    ${nav(active, "site-shell-links", "Primary navigation")}</nav>
    <a class="site-shell-cta" href="/app" data-track="Header: try it free">Try it free</a>
    <details class="site-shell-mobile">
      <summary aria-label="Open site navigation"></summary>
      ${nav(active, "site-shell-panel", "Mobile navigation")}
        <a class="site-shell-cta" href="/app" data-track="Mobile menu: try it free">Try it free</a>
      </nav>
    </details>
  </div>
</header>

<main class="site-page-main" id="main">
${body}
</main>

<footer class="wrap">
  <p class="site-footer-links"><a href="/blog">Blog</a><a href="/hymns">Hymns in Tonic Solfa</a><a href="/app">Web app</a><a href="/terms">Terms</a><a href="/privacy">Privacy</a><a href="mailto:hello@notefusion.studio">Contact</a></p>
  <p>NoteFusion. Hear it. See it. Notate it. &copy; 2026 NoteFusion.</p>
</footer>
${scripts}
<script src="/assets/track.js?v=${ASSET_VERSION.track}" defer></script>
</body>
</html>
`;
}

export function breadcrumbs(items) {
  return `<nav class="crumbs" aria-label="Breadcrumb"><ol>${items.map(([href, text], i) =>
    i === items.length - 1 ? `<li><span aria-current="page">${escapeHtml(text)}</span></li>` : `<li><a href="${href}">${escapeHtml(text)}</a></li>`).join("")}</ol></nav>`;
}

export function breadcrumbLd(items) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map(([href, text], i) => ({ "@type": "ListItem", position: i + 1, name: text, item: ORIGIN + (href === "/" ? "/" : href) })),
  };
}

