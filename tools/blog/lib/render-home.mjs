// The home page's sample sheet, between its markers in web-site/index.html: the opening line of a hymn
// from the hymnal as the product writes it, the engine's solfa grid with the words, and the same bars on
// the staff (web-site/assets/sample-staff.svg, engraved by the pinned OSMD the hymn pages and the web app
// use). Real output, never a drawing of one.
import { escapeHtml } from "./util.mjs";
import { gridHtml } from "./grid-html.mjs";

export const SHEET_START = "<!-- home-sheet:start -->", SHEET_END = "<!-- home-sheet:end -->";
export const SAMPLE_HYMN = "amazing-grace";

/** `hymn` has been through prepareHymn (its `view` holds the lines of bars). */
export function renderHomeSheet(hymn) {
  const v = hymn.view;
  return `${SHEET_START}
<!-- Generated by tools/blog/build.mjs from content/hymns/${SAMPLE_HYMN}. Edit the hymn, not this block. -->
<figure class="sheet" aria-labelledby="sheet-title">
  <div class="sheet-head">
    <p class="sheet-title" id="sheet-title">${escapeHtml(hymn.title)}</p>
    <p class="sheet-meta"><span>${escapeHtml(v.header)}</span><span>${escapeHtml(v.key)}</span><span>${escapeHtml(v.time)}</span></p>
  </div>
  <div class="sheet-solfa">
${gridHtml([v.lines[0]], { words: true })}
  </div>
  <div class="sheet-staff"><img src="/assets/sample-staff.svg" width="613" height="236" alt="The same bars on the treble staff in ${escapeHtml(v.key)}, with the words under the notes"></div>
  <figcaption class="sheet-foot"><span>The opening line, as NoteFusion writes it: solfa above, staff below.</span> <a href="/hymns/${SAMPLE_HYMN}">Open the whole hymn</a></figcaption>
</figure>
${SHEET_END}`;
}
