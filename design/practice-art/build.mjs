// The Practice art: Doh the doh bird (with the poses he takes outside Practice and their blink twins), the level emblems, the badge stickers, the streak flame and freeze, the stars,
// the confetti pieces, the track-picker scenes, the empty states and the Christmas season's cap and snowflake. All of it is our own original SVG, drawn by
// these modules; this script writes the copies the apps ship:
//
//   web-site/assets/practice-art/<name>.svg            — the web app's Practice view loads them as <img> on demand
//   mobile/src/components/practice/art/svgs.ts         — the phone draws them with react-native-svg's SvgXml
//
//   node design/practice-art/build.mjs          write both
//   node design/practice-art/build.mjs --check  exit 1 if either is out of date (web-site/tests/practice-art.test.mjs)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { birdSvg, blinkSvg, BLINKS, POSES } from "./mascot.mjs";
import { emblem, LEVELS } from "./emblems.mjs";
import { BADGES, sticker } from "./badges.mjs";
import * as B from "./bits.mjs";
import * as S from "./scenes.mjs";
import * as X from "./season.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const WEB_DIR = path.join(ROOT, "web-site/assets/practice-art");
export const MOBILE_FILE = path.join(ROOT, "mobile/src/components/practice/art/svgs.ts");

const slug = (s) => s.toLowerCase().replace(/[^a-z]+/g, "-").replace(/-$/, "");

/** Every asset the apps use, by name: [name, svg]. */
export function assets() {
  const out = [];
  for (const k of Object.keys(POSES)) out.push([`doh-${k}`, birdSvg(k)]);
  for (const k of BLINKS) out.push([`doh-${k}-blink`, blinkSvg(k)]);
  out.push(["doh-avatar", S.avatar()]);
  LEVELS.forEach((L, i) => out.push([`level-${i + 1}-${slug(L.name)}`, emblem(i)]));
  for (const b of BADGES) out.push([`badge-${b.id}`, sticker(b)], [`badge-${b.id}-locked`, sticker(b, true)]);
  out.push(["flame-active", B.streak.active()], ["flame-at-risk", B.streak.atRisk()], ["flame-out", B.streak.out()], ["freeze", B.freeze()]);
  for (const n of [1, 2, 3]) out.push([`stars-${n}`, B.stars(n)]);
  for (const [k, f] of Object.entries(B.CONFETTI)) out.push([`confetti-${k}`, f()]);
  out.push(["track-playful", S.playful()], ["track-focused", S.focused()]);
  out.push(["empty-no-drill", S.noDrill()], ["empty-offline", S.offline()]);
  // The Christmas season, shown only while it is on: the cap laid over the brand mark and Doh, and the Carol singer's
  // snowflake (its sticker is with the badges).
  out.push(["season-cap", X.cap()], ["confetti-snowflake", X.snowflake()]);
  return out.map(([n, s]) => [n, minify(s)]);
}

/** Lean output: no whitespace between tags, numbers at one decimal place, no leading zeros. */
export function minify(svg) {
  return svg
    .replace(/>\s+</g, "><")
    .replace(/\s{2,}/g, " ")
    .replace(/(-?\d+\.\d{2,})/g, (m) => String(Math.round(Number(m) * 10) / 10))
    .replace(/([\s,"(A-Za-z-])0\.(\d)/g, "$1.$2")
    .trim();
}

/**
 * The phone's copy: one string per asset, gradient and clip ids prefixed with the asset's name, because a page of
 * SVGs on the web build of the app shares one id space.
 */
export function mobileModule(list) {
  const lines = list.map(([n, s]) => {
    const p = n.replace(/[^a-z0-9]/gi, "");
    const scoped = s
      .replace(/ xmlns="[^"]*"/, "")
      .replace(/id="([^"]+)"/g, `id="${p}-$1"`)
      .replace(/url\(#([^)]+)\)/g, `url(#${p}-$1)`)
      .replace(/"/g, "'"); // SvgXml reads either quote; single ones need no escaping in the module
    return `  ${JSON.stringify(n)}: ${JSON.stringify(scoped)},`;
  });
  return [
    "// Generated by design/practice-art/build.mjs — do not edit. The Practice art as SVG strings, drawn with",
    "// react-native-svg's SvgXml (components/practice/Art.tsx). The web app ships the same art as files in",
    "// web-site/assets/practice-art/.",
    "export const ART = {",
    ...lines,
    "} as const;",
    "",
    "export type ArtName = keyof typeof ART;",
    "",
  ].join("\n");
}

function write() {
  const list = assets();
  fs.rmSync(WEB_DIR, { recursive: true, force: true });
  fs.mkdirSync(WEB_DIR, { recursive: true });
  for (const [n, s] of list) fs.writeFileSync(path.join(WEB_DIR, `${n}.svg`), s + "\n");
  fs.mkdirSync(path.dirname(MOBILE_FILE), { recursive: true });
  fs.writeFileSync(MOBILE_FILE, mobileModule(list));
  const bytes = list.reduce((t, [, s]) => t + Buffer.byteLength(s), 0);
  console.log(`${list.length} assets, ${(bytes / 1024).toFixed(1)} KB of SVG`);
}

/** The files that differ from a fresh build (empty when up to date). */
export function stale() {
  const list = assets(), out = [];
  const want = new Map(list.map(([n, s]) => [`${n}.svg`, s + "\n"]));
  const have = fs.existsSync(WEB_DIR) ? fs.readdirSync(WEB_DIR) : [];
  for (const f of have) if (!want.has(f)) out.push(`web-site/assets/practice-art/${f} (no longer built)`);
  for (const [f, s] of want) {
    const p = path.join(WEB_DIR, f);
    if (!fs.existsSync(p) || fs.readFileSync(p, "utf8") !== s) out.push(`web-site/assets/practice-art/${f}`);
  }
  if (!fs.existsSync(MOBILE_FILE) || fs.readFileSync(MOBILE_FILE, "utf8") !== mobileModule(list)) out.push("mobile/src/components/practice/art/svgs.ts");
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const s = stale();
    if (s.length) { console.error(`Out of date; run node design/practice-art/build.mjs:\n  ${s.join("\n  ")}`); process.exit(1); }
    console.log("Practice art up to date.");
  } else write();
}
